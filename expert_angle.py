def get_candidates(perspective: str) -> list[str]:
    """
    CORE HARI視点キーワードに一致する候補リストを返す。
    一致しない場合は汎用候補を返す。
    """
    for key, angles in _ANGLE_MASTER.items():
        if key in perspective:
            return angles
    return _FALLBACK_ANGLES


def auto_select(perspective: str, n: int = 2) -> list[str]:
    """
    Topicに対して自動で上位 n 件の Expert Angle を選んで返す。
    候補の先頭 n 件を使う（リストは視点に対して最重要順で定義済み）。
    """
    candidates = get_candidates(perspective)
    return candidates[:n]


def select_expert_angles(
    perspective: str,
    skip_if_no_tty: bool = True,
) -> list[str]:
    """
    Expert Angle を自動選択して表示し、追加/削除だけ操作できる。

    Enter → 自動選択をそのまま採用
    +N  → 番号 N を追加（例: +3）
    -N  → 番号 N を削除（例: -1）
    複数指定可（例: +3 -1）
    """
    candidates = get_candidates(perspective)
    current = auto_select(perspective, n=2)

    if skip_if_no_tty and not sys.stdin.isatty():
        return current

    def _show(cur: list[str]) -> None:
        auto_set = set(current)
        print()
        print("─" * 60)
        print("  【Expert Angle】")
        print(f"  CORE HARI視点: {perspective}")
        print()
        for i, angle in enumerate(candidates, 1):
            if angle in cur:
                marker = "◎"
            elif angle in auto_set:
                marker = "○"
            else:
                marker = " "
            print(f"  {marker} [{i}] {angle}")
        print()
        selected_str = "  / ".join(cur) if cur else "（なし）"
        print(f"  現在の選択: {selected_str}")
        print()
        print("  Enter → このまま採用")
        print("  +番号 で追加 / -番号 で削除（例: +3 -1）")
        print("─" * 60)

    _show(current)

    try:
        raw = input("  > ").strip()
    except (EOFError, KeyboardInterrupt):
        print()
        return current

    if not raw:
        return current

    result = list(current)
    for token in raw.split():
        if token.startswith("+") and token[1:].isdigit():
            idx = int(token[1:]) - 1
            if 0 <= idx < len(candidates):
                item = candidates[idx]
                if item not in result:
                    result.append(item)
        elif token.startswith("-") and token[1:].isdigit():
            idx = int(token[1:]) - 1
            if 0 <= idx < len(candidates):
                item = candidates[idx]
                if item in result:
                    result.remove(item)

    return result if result else current
